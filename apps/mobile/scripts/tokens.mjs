// The phone's colours are the desktop's: this reads the design tokens in the desktop's stylesheet
// (src/renderer/styles/app.css, its [data-theme] blocks) and writes them as Uniwind theme
// variables (src/theme.css), so `bg-bg-2` or `text-text-3` here is `var(--bg-2)` / `var(--text-3)`
// there. Run after changing the desktop's palette: `npm run tokens` (`--check` fails if stale).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(app, "../../src/renderer/styles/app.css"), "utf8");
const out = join(app, "src/theme.css");

function block(theme) {
  const m = new RegExp(`\\[data-theme="${theme}"\\]\\s*\\{([^}]*)\\}`).exec(css);
  if (!m) throw new Error(`No [data-theme="${theme}"] block in app.css`);
  const vars = [];
  for (const [, name, value] of m[1].matchAll(/--([\w-]+):\s*([^;]+);/g)) {
    // Colours only: shadows and the like don't carry over to native views.
    if (/^(#[0-9a-f]{3,8}|rgba?\([^)]*\))$/i.test(value.trim())) vars.push(`      --color-${name}: ${value.trim()};`);
  }
  return vars.join("\n");
}

const text = `/* Generated by scripts/tokens.mjs from the desktop's src/renderer/styles/app.css. Don't edit. */
@layer theme {
  :root {
    @variant dark {
${block("dark")}
    }
    @variant light {
${block("light")}
    }
  }
}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/theme.css is out of date with the desktop's app.css: run npm run tokens");
    process.exit(1);
  }
} else writeFileSync(out, text);
